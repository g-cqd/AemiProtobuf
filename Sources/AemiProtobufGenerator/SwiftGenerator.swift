public import AemiProtobufSchema

/// Swift source from a descriptor set: one file per `.proto`, each message a `@ProtoMessage` struct (roadmap 0028).
///
/// Every field takes the presence, encoding and enumeration semantics its syntax or edition gives it: explicit presence is an
/// `Optional`, `required` and `LEGACY_REQUIRED` are `required: true`, a closed enumeration is a raw-value one and an open one has an
/// `unrecognized` case, a delimited message is a group, an expanded repeated number is `packed: false`. Bytes are `[UInt8]`, so
/// no nested type can shadow `Foundation.Data`. A field whose message can lead back to its own is `@Indirect`. An extension
/// declared in the same file as the message it extends is a field of it, except on a MessageSet, whose extensions stay unknown
/// fields. Fields are declared in number order, so a message writes the bytes C++ writes.
public enum SwiftGenerator {
    public static func generate(
        _ set: FileDescriptorSet, files: [String], options: GeneratorOptions = GeneratorOptions()
    ) throws(GeneratorError) -> [GeneratedFile] {
        let symbols = SymbolTable(set)
        let extensions = sameFileExtensions(set, symbols)
        let recursion = RecursionAnalysis(edges: valueEdges(symbols, extensions))
        let emitter = MessageEmitter(
            symbols: symbols, planner: FieldPlanner(symbols: symbols, recursion: recursion), extensions: extensions,
            options: options)
        var output: [GeneratedFile] = []
        for name in files {
            guard let file = set.files.first(where: { $0.name == name }) else { throw .unknownFile(name) }
            var lines = [
                "// Generated by protoc-gen-aemi from \(name). Do not edit.", "// swift-format-ignore-file",
                "// swiftlint:disable all", "", "import AemiProtobuf"
            ]
            let scope = file.package.isEmpty ? "" : "." + file.package
            let access = options.visibility == .public ? "public " : ""
            for enumeration in file.enums {
                let open = symbols.isOpen(scope + "." + enumeration.name)
                let swiftName = SwiftNaming.prefix(package: file.package) + enumeration.name
                lines += [""] + EnumEmitter.emit(enumeration, open: open, access: access, name: swiftName)
            }
            for message in file.messages {
                let swiftName = SwiftNaming.prefix(package: file.package) + message.name
                lines += [""] + (try emitter.emit(scope + "." + message.name, name: swiftName))
            }
            let base = name.hasSuffix(".proto") ? String(name.dropLast(6)) : name
            output.append(GeneratedFile(name: base + ".aemi.swift", content: indent(lines)))
        }
        return output
    }

    /// Extensions declared at a file's top level whose message is in the same file and is not a MessageSet.
    private static func sameFileExtensions(_ set: FileDescriptorSet, _ symbols: SymbolTable) -> [String:
        [FieldDescriptor]]
    {
        var result: [String: [FieldDescriptor]] = [:]
        for file in set.files {
            for field in file.extensions {
                guard let symbol = symbols[field.extendee], symbol.file.name == file.name,
                    case .message(let message) = symbol.declaration, !message.messageSetWireFormat
                else { continue }
                var copy = field
                copy.extendee = ""
                result[field.extendee, default: []].append(copy)
            }
        }
        return result
    }

    /// For each message, the messages its singular fields and oneof members hold by value.
    private static func valueEdges(_ symbols: SymbolTable, _ extensions: [String: [FieldDescriptor]]) -> [String: Set<
        String
    >] {
        var edges: [String: Set<String>] = [:]
        for (fullName, symbol) in symbols.symbols {
            guard case .message(let message) = symbol.declaration else { continue }
            var targets: Set<String> = []
            for field in message.fields + (extensions[fullName] ?? [])
            where field.label != .repeated && (field.type == .message || field.type == .group) {
                targets.insert(field.typeName)
            }
            edges[fullName] = targets
        }
        return edges
    }

    /// Four spaces a level, from the braces that open and close a line.
    private static func indent(_ lines: [String]) -> String {
        var depth = 0
        var result = ""
        for line in lines {
            if line.hasPrefix("}") { depth = max(0, depth - 1) }
            result += line.isEmpty ? "\n" : String(repeating: "    ", count: depth) + line + "\n"
            if line.hasSuffix("{") { depth += 1 }
        }
        return result
    }
}
