#!/usr/bin/env bash
# Embeds descriptor.proto's descriptor set in AemiProtobufSchema (roadmap 0002): the option messages the compiler interprets
# options against when a file does not import descriptor.proto itself. Run when protoc moves.
#   PROTOBUF_SOURCE=/path/to/protobuf Scripts/generate-descriptor-proto.sh
set -euo pipefail
SOURCE=${PROTOBUF_SOURCE:?set PROTOBUF_SOURCE to a protobuf checkout}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/Sources/AemiProtobufSchema/GeneratedDescriptorProto.swift"
SET=$(mktemp)
trap 'rm -f "$SET"' EXIT
protoc -I"$SOURCE/src" --descriptor_set_out="$SET" google/protobuf/descriptor.proto
{
    echo '// Generated by Scripts/generate-descriptor-proto.sh from protoc'"'"'s google/protobuf/descriptor.proto. Do not edit.'
    echo ''
    echo 'enum GeneratedDescriptorProto {'
    echo '    /// The descriptor set of `google/protobuf/descriptor.proto`, base64.'
    echo '    static let base64 = """'
    base64 < "$SET" | tr -d '\n' | fold -w 108 | sed 's/^/        /'
    echo ''
    echo '        """'
    echo '}'
} > "$OUT"
echo "wrote $OUT"
