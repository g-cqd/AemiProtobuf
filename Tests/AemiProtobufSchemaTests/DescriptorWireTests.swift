import AemiProtobufCore
import AemiProtobufSchema
import Foundation
import Testing

struct DescriptorWireTests {
    @Test func `sample pb generated by protoc decodes into FileDescriptorSet with expected structure`() throws {
        let url = try #require(
            Bundle.module.url(forResource: "sample", withExtension: "pb", subdirectory: "Resources"))
        let data = try Data(contentsOf: url)
        let bytes = [UInt8](data)

        let set = try FileDescriptorSet.decode(from: bytes)
        #expect(set.files.count == 1)

        let file = try #require(set.files.first)
        #expect(file.package == "test.sample")
        #expect(file.syntax == "proto3")
        #expect(file.messages.count == 2)

        let address = file.messages.first { $0.name == "Address" }
        #expect(address != nil)
        #expect(address?.fields.count == 3)

        let street = address?.fields.first { $0.name == "street" }
        #expect(street?.number == 1)
        #expect(street?.type == .string)

        let zip = address?.fields.first { $0.name == "zip" }
        #expect(zip?.number == 3)
        #expect(zip?.type == .int32)

        let user = file.messages.first { $0.name == "User" }
        #expect(user != nil)
        #expect(user?.fields.count == 10)

        let tags = user?.fields.first { $0.name == "tags" }
        #expect(tags?.label == .repeated)
        #expect(tags?.type == .string)

        let addrField = user?.fields.first { $0.name == "address" }
        #expect(addrField?.type == .message)
    }

    @Test func `FileDescriptorSet encodes and decodes round-trip`() throws {
        let original = FileDescriptorSet(files: [
            FileDescriptor(
                name: "test.proto",
                package: "pkg",
                syntax: "proto3",
                messages: [
                    MessageDescriptor(
                        name: "Msg",
                        fields: [
                            FieldDescriptor(name: "f1", number: 1, label: .optional, type: .int32),
                            FieldDescriptor(name: "f2", number: 2, label: .repeated, type: .string)
                        ]
                    )
                ],
                enums: [
                    EnumDescriptor(
                        name: "Status",
                        values: [
                            EnumValueDescriptor(name: "UNKNOWN", number: 0),
                            EnumValueDescriptor(name: "OK", number: 1)
                        ]
                    )
                ]
            )
        ])

        let bytes = try original.encode()
        let decoded = try FileDescriptorSet.decode(from: bytes)
        #expect(decoded == original)
    }
}
